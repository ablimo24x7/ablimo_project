export function getIcon(name: string | undefined, className?: string): React.ReactNode {
  if (!name) return null;
  const classes = iconClassMap[name];
  if (!classes) return null;
  return <i className={`${classes} ${className || ""}`.trim()} aria-hidden="true" />;
}

export const ICON_OPTIONS = Object.keys(iconClassMap).map((name) => ({
  value: name,
  label: name
    .replace(/([a-z0-9])([A-Z])/g, "$1 $2")
    .replace(/([A-Z])([A-Z][a-z])/g, "$1 $2"),
}));
