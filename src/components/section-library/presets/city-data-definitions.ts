export function getCityConfig(citySlug: string): CityPresetConfig | undefined {
  const normalized = citySlug.trim().toLowerCase();
  const direct = ALL_CITY_CONFIGS[normalized];
  if (direct) return direct;
  const aliasKey = CITY_SLUG_ALIASES[normalized];
  if (aliasKey) return ALL_CITY_CONFIGS[aliasKey];
  return undefined;
}

