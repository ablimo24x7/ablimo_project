import type { Metadata } from "next";
import IndustryPage, {
  buildIndustryContent,
  type IndustryPageTexts,
  type IndustryStructure,
} from "../_components/IndustryPage";
import {
  getDictionary,
  hasLocale,
  defaultLocale,
  type Locale,
} from "@/app/[lang]/dictionaries";

export async function generateMetadata({
  params,
}: {
  params: Promise<{ lang: string }>;
}): Promise<Metadata> {
  const { lang } = await params;
  const locale: Locale = hasLocale(lang) ? lang : defaultLocale;
  const dict = await getDictionary(locale);
  return {
    title: dict.industryPages.aviation.metadata.title,
    description: dict.industryPages.aviation.metadata.description,
  };
}

